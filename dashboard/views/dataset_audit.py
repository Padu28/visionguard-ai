import numpy as np
import pandas as pd
import plotly.graph_objects as go
import streamlit as st
import theme as t

import data

t.hero("Dataset Audit", "Class balance, the instance-level split that prevents near-duplicate leakage, defect-area "
       "statistics and a browsable gallery with ground-truth masks.", badge="Synthetic · NEU-style", icon="🖼️")

s = data.summary()
a = s["audit"]
meta = data.metadata()
t.kpis([
    ("Images", f"{a['n_images']:,}", f"{a['image_shape'][0]}×{a['image_shape'][1]} grayscale", "🖼️", t.PRIMARY),
    ("Steel sheets", f"{a['instances']}", "split unit", "🧱", t.SECONDARY),
    ("Leaked sheets", f"{a['instance_leakage']}", "train ∩ test", "🔒", t.SUCCESS),
    ("Mean defect area", f"{a['mean_defect_area']:.1%}", "of image pixels", "📐", t.ACCENT),
])

c1, c2 = st.columns([1.2, 1])
with c1:
    t.section("Class counts by split")
    bs = pd.DataFrame(a["by_split"]).T.reindex(["train", "validation", "test"])
    fig = go.Figure()
    for cls in s["classes"]:
        fig.add_trace(go.Bar(x=bs.index, y=bs[cls], name=cls, marker_color=t.CLASS_COLORS[cls]))
    fig.update_layout(barmode="stack")
    st.plotly_chart(t.style_fig(fig, 340), use_container_width=True)
with c2:
    t.section("Defect area distribution")
    d = meta[meta.label > 0]
    fig = go.Figure()
    for cls, g in d.groupby("class_name"):
        fig.add_trace(go.Box(y=g.defect_area * 100, name=cls, marker_color=t.CLASS_COLORS[cls], boxmean=True))
    fig.update_layout(yaxis_title="% of pixels", showlegend=False)
    st.plotly_chart(t.style_fig(fig, 340), use_container_width=True)

t.section("Gallery", "toggle masks to see exactly where each defect is")
c1, c2, c3 = st.columns([1, 1, 2])
cls = c1.selectbox("Class", s["classes"])
split = c2.selectbox("Split", ["train", "validation", "test"])
show_mask = c3.toggle("Overlay ground-truth mask", True)
pool = meta[(meta.class_name == cls) & (meta.split == split)].head(12)
cols = st.columns(6)
for k, row in enumerate(pool.itertuples()):
    img = data.image(row.path)
    if show_mask and row.label > 0:
        m = data.mask(row.path)
        rgb = np.stack([img] * 3, -1)
        rgb[m > 0] = 0.55 * rgb[m > 0] + 0.45 * np.array([0.06, 0.73, 0.51])
        img = rgb
    cols[k % 6].image(img, caption=f"sheet {row.instance}", use_container_width=True, clamp=True)

